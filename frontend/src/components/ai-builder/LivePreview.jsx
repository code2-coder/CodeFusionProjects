import React from 'react';

// Helper to get AI image
const getAiImage = (prompt, width=800, height=600) => {
  if (!prompt) return `https://picsum.photos/${width}/${height}`;
  return `https://image.pollinations.ai/prompt/${encodeURIComponent(prompt)}?width=${width}&height=${height}&nologo=true`;
};

// Basic Placeholder Components
const Hero = ({ branding, props = {} }) => (
  <div style={{ backgroundColor: branding.colors.primary, color: branding.colors.text }} className="relative text-center rounded-lg my-4 overflow-hidden group">
    {props.imagePrompt && (
      <div className="absolute inset-0 z-0">
        <img src={getAiImage(props.imagePrompt, 1200, 600)} alt="Hero Background" className="w-full h-full object-cover opacity-30 group-hover:opacity-40 transition-opacity duration-700" />
      </div>
    )}
    <div className="relative z-10 py-24 px-8">
      <h1 className="text-5xl font-bold mb-6">{props.title || `Welcome to ${branding.theme} Theme`}</h1>
      <p className="text-xl max-w-2xl mx-auto opacity-90">{props.description || 'This is an AI generated Hero section. It uses your brand primary color.'}</p>
      <button className="mt-8 px-6 py-3 bg-white text-black font-semibold rounded-full hover:bg-gray-100 transition-colors">
        Get Started
      </button>
    </div>
  </div>
);

