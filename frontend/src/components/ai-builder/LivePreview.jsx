const UnknownComponent = ({ type, branding, props = {} }) => (
  <div className="p-6 border-2 border-dashed border-gray-400 text-gray-500 text-center my-4 rounded-lg bg-gray-50 dark:bg-gray-800">
    <p>Component: <strong>{type}</strong></p>
    {props.title && <h3 className="text-xl font-bold mt-2 text-black dark:text-white">{props.title}</h3>}
    {props.description && <p className="mt-2 text-sm text-black dark:text-white opacity-80">{props.description}</p>}
    {props.imagePrompt && (
      <img src={getAiImage(props.imagePrompt, 600, 300)} alt={props.title} className="w-full h-48 object-cover rounded mt-4" />
    )}
  </div>
);

const componentMap = {
  'Hero': Hero,
  'Features': Features,
  'Testimonials': Testimonials,
  'Footer': Footer,
  'Contact': Contact
};

const LivePreview = ({ page, branding }) => {
  if (!page) return <div className="p-8 text-center text-gray-500">No page selected.</div>;

  const fontStyle = {
    fontFamily: branding?.fonts?.body || 'Inter, sans-serif',
    backgroundColor: branding?.colors?.background || '#ffffff',
    color: branding?.colors?.text || '#000000',
    minHeight: '100%',
  };

  return (
    <div style={fontStyle} className="rounded-lg shadow-2xl overflow-hidden transition-colors duration-500">
      {page.components && page.components.length > 0 ? (
        page.components.map((comp, idx) => {
          const Component = componentMap[comp.type] || UnknownComponent;
          return <Component key={comp._id || idx} type={comp.type} branding={branding} props={comp.props} />;
        })
      ) : (
        <div className="p-12 text-center opacity-60">
          <h2 className="text-2xl font-bold mb-2">{page.title}</h2>
          <p>No components generated for this page yet.</p>
        </div>
      )}
    </div>
  );
};

export default LivePreview;
